@dataclass(frozen=True)
class LeaderboardScores:
    """Both leaderboard columns, parsed once per run."""

    open_scores: dict[str, float]
    mcq_scores: dict[str, float]

    @property
    def labels(self) -> list[str]:
        return sorted(set(self.open_scores) | set(self.mcq_scores))


def _parse_scores(page_html: str) -> LeaderboardScores:
    return LeaderboardScores(
        open_scores={
            row.model_name: row.score
            for row in _extract_section_rows(page_html, OPEN_SECTION_TITLE)
        },
        mcq_scores={
            row.model_name: row.score
            for row in _extract_section_rows(page_html, MCQ_SECTION_TITLE)
        },
    )


def _build_log(
    label: str,
    scores: LeaderboardScores,
    retrieved_ts: str,
    url: str,
) -> EvaluationLog:
    """One EvaluationLog for one leaderboard label.

    Raises:
        ValueError: the label has no identity mapping, or no score at all.
    """
    identity = _model_identity(label)
    evaluation_results: list[EvaluationResult] = []
    if label in scores.open_scores:
        evaluation_results.append(
            _build_open_question_result(
                scores.open_scores[label], label, identity
            )
        )
    if label in scores.mcq_scores:
        evaluation_results.append(
            _build_mcq_result(scores.mcq_scores[label], label, identity)
        )
    if not evaluation_results:
        raise ValueError(f'No leaderboard score for model: {label}')

    return EvaluationLog(
        schema_version=SCHEMA_VERSION,
        # Keyed on the RAW leaderboard label, not the resolved canonical id: a
        # registry re-mapping must not change this record's identity.
        evaluation_id=f'{BENCHMARK_KEY}/{label}/{retrieved_ts}',
        retrieved_timestamp=retrieved_ts,
        eval_library=_eval_library(identity),
        source_metadata=SourceMetadata(
            source_name='LEXam Leaderboard',
            source_type=SourceType.documentation,
            source_organization_name='LEXam-Benchmark',
            source_organization_url=GITHUB_REPO_URL,
            # Relative to the model developer, not to the benchmark.
            evaluator_relationship=EvaluatorRelationship.third_party,
            additional_details={
                'leaderboard_page': LEADERBOARD_PAGE_URL,
                'source_html': url,
                'citation': PAPER_URL,
            },
        ),
        model_info=ModelInfo(
            name=label,
            id=identity.model_id,
            developer=identity.developer,
            inference_platform=identity.inference_platform,
            inference_engine=identity.inference_engine,
            additional_details=_model_details(identity, label),
        ),
        evaluation_results=evaluation_results,
    )


class LEXamAdapter:
    """Converts LEXam public leaderboard rows into EvaluationLog objects."""

    def fetch_leaderboard(
        self,
        html: str | None = None,
        url: str = LEADERBOARD_URL,
    ) -> list[EvaluationLog]:
        """Fetch the LEXam leaderboard and return one log per model.

        Args:
            html: Optional pre-fetched HTML (used in tests).
            url: Leaderboard HTML URL when *html* is not provided.

        Returns:
            One log per model, carrying whichever of the two metrics the
            leaderboard publishes for it. All records of a run share one
            retrieval timestamp.

        Raises:
            ValueError: a label has no identity mapping. Use
                `fetch_leaderboard_result` to report them instead.
        """
        page_html = html if html is not None else _fetch_html(url)
        scores = _parse_scores(page_html)
        retrieved_ts = get_current_unix_timestamp()
        logs = [
            _build_log(label, scores, retrieved_ts, url)
            for label in scores.labels
        ]
        logger.info('Converted %d LEXam leaderboard model(s).', len(logs))
        return logs

    def fetch_leaderboard_result(
        self,
        html: str | None = None,
        url: str = LEADERBOARD_URL,
    ) -> SourceConversionResult[EvaluationLog]:
        """Convert the leaderboard, recording unmapped rows as failures.

        An unmapped label lands in the provenance report instead of aborting
        the run; `raise_if_incomplete` still fails the command afterwards.
        """
        page_html = html if html is not None else _fetch_html(url)
        scores = _parse_scores(page_html)
        retrieved_ts = get_current_unix_timestamp()

        records: list[EvaluationLog] = []
        failures: list[SourceRecordFailure] = []
        for label in scores.labels:
            try:
                records.append(_build_log(label, scores, retrieved_ts, url))
            except ValueError as exc:
                failures.append(
                    SourceRecordFailure(
                        source_ref=f'LEXam leaderboard row {label!r}',
                        reason=str(exc),
                        source_record={'model_name': label},
                    )
                )

        logger.info('Converted %d LEXam leaderboard model(s).', len(records))
        return SourceConversionResult(
            source_name='LEXam Leaderboard',
            total_records=len(scores.labels),
            records=records,
            failures=failures,
        )


def parse_args(argv: list[str] | None = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description=(
            'Convert the LEXam public leaderboard to Every Eval Ever records.'
        ),
    )
    parser.add_argument(
        '--input-html',
        type=Path,
        help=(
            'Read leaderboard HTML from a file instead of fetching it live '
            '(useful for offline smoke runs).'
        ),
    )
    parser.add_argument(
        '--output-dir',
        type=Path,
        default=Path(DEFAULT_OUTPUT_DIR),
        help=f'Output directory (default: {DEFAULT_OUTPUT_DIR}).',
    )
    parser.add_argument(
        '--source-url',
        default=LEADERBOARD_URL,
        help=f'Leaderboard HTML URL (default: {LEADERBOARD_URL}).',
    )
    parser.add_argument(
        '--failure-report',
        type=Path,
        help='Where to write the provenance report when rows are rejected.',
    )
    return parser.parse_args(argv)


def export(logs: list[EvaluationLog], output_dir: Path | str) -> list[Path]:
    return publish_evaluation_logs(
        logs, output_dir, [str(uuid.uuid4()) for _ in logs]
    )


def run(args: argparse.Namespace) -> int:
    html = (
        args.input_html.read_text(encoding='utf-8')
        if args.input_html is not None
        else None
    )
    result = LEXamAdapter().fetch_leaderboard_result(
        html=html, url=args.source_url
    )
    paths = export(result.records, args.output_dir)
    for path in paths:
        print(path)
    if result.failures:
        report_path = save_failure_report(
            result,
            args.failure_report or default_failure_report_path(args.output_dir),
        )
        print(f'Failure report: {report_path}')
        result.raise_if_incomplete()
    return len(paths)


if __name__ == '__main__':
    written = run(parse_args())
    print(f'Wrote {written} LEXam model log(s).')

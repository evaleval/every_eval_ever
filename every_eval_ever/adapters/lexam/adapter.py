def _extract_section_rows(
    html: str, section_title: str
) -> list[LeaderboardRow]:
    """Parse model/score rows from the table under *section_title*.

    Bounded by the next section heading, so a section whose own table is
    missing cannot consume the following section's table.
    """
    title_idx = html.find(section_title)
    if title_idx == -1:
        raise ValueError(f'Leaderboard section not found: {section_title}')

    heading_end = html.find('</h1>', title_idx)
    search_from = title_idx if heading_end == -1 else heading_end
    next_heading = html.find('<h1', search_from)
    section_end = len(html) if next_heading == -1 else next_heading

    table_start = html.find('<table', search_from, section_end)
    if table_start == -1:
        raise ValueError(f'No table found in section: {section_title}')

    table_end = html.find('</table>', table_start, section_end)
    if table_end == -1:
        raise ValueError(f'Table not closed within section: {section_title}')

    table_html = html[table_start:table_end]
    row_re = re.compile(
        r'<tr[^>]*>\s*'
        r'<td[^>]*>(?:<strong>)?(\d+)(?:</strong>)?</td>\s*'
        r'<td[^>]*>(.*?)</td>\s*'
        r'<td[^>]*>(?:<strong>)?([\d.]+)(?:</strong>)?</td>\s*'
        r'</tr>',
        re.DOTALL | re.IGNORECASE,
    )

    # Compared against the parsed rows below: an unreadable row must fail the
    # section rather than shorten the leaderboard.
    data_rows = [
        block
        for block in re.findall(
            r'<tr[^>]*>.*?</tr>', table_html, re.DOTALL | re.IGNORECASE
        )
        if '<td' in block.lower()
    ]

    rows: list[LeaderboardRow] = []
    for row_match in row_re.finditer(table_html):
        _, model_cell, score_text = row_match.groups()
        model_name = re.sub(r'<[^>]+>', '', model_cell)
        model_name = _clean_model_name(model_name)
        if not model_name:
            continue
        rows.append(
            LeaderboardRow(
                model_name=model_name,
                score=float(score_text),
            )
        )
    if not rows:
        raise ValueError(f'No leaderboard rows found for: {section_title}')
    if len(rows) != len(data_rows):
        raise ValueError(
            f'Read {len(rows)} of {len(data_rows)} data rows in section: '
            f'{section_title}'
        )
    repeated = sorted(
        name
        for name, count in Counter(r.model_name for r in rows).items()
        if count > 1
    )
    if repeated:
        raise ValueError(
            f'Duplicate model rows in section {section_title}: '
            f'{", ".join(repeated)}'
        )
    return rows



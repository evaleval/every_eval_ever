@dataclass(frozen=True)
class MetricSpec:
    """One metric as the eval-card-registry defines it.

    Bounds and direction are the registry entry's, not the scale the
    leaderboard prints; `percent_divisor` maps the published percentage onto
    the canonical scale.
    """

    metric_id: str
    metric_name: str
    metric_kind: str
    unit: str
    canonical_min: float
    canonical_max: float
    percent_divisor: float

    @property
    def review_status(self) -> str:
        """The registry's own review status, read from the pinned snapshot."""
        metrics = registry_snapshot().get('metrics', {})
        return metrics.get(self.metric_id, {}).get('review_status', 'unknown')



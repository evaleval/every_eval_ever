@dataclass(frozen=True)
class ModelIdentity:
    """Identity for one LEXam leaderboard label.

    `model_id` is the join key written to `model_info.id`, resolved against the
    eval-card-registry. `id_source` records how:

    * `registry_alias` — a registered alias maps this label to this canonical.
    * `registry_canonical` — the label matches a reviewed canonical one-to-one,
      but the alias itself is not registered yet.
    * `hf_canonical` — the registry has no canonical for the evaluated
      checkpoint, so the Hugging Face repo id is used, with any draft the
      registry does return in `registry_canonical_id`.

    `developer_org_id` is the registry's normalized company org. It differs
    from the id prefix whenever the id is a Hugging Face repo id (for example
    `Qwen/Qwen3-32B` under org `alibaba`), and the datastore path follows the
    prefix rather than this field.
    """

    model_id: str
    developer_org_id: str
    availability: str
    id_source: str
    registry_canonical_id: str | None = None
    api_model_name: str | None = None
    note: str | None = None
    #: The model string LEXam's runner sends, when its config names this label.
    served_model: str | None = None
    #: Set when the runner's endpoint and appendix F's rule disagree.
    served_model_note: str | None = None
    #: §F LLM Endpoints. `None` means it was served locally under vLLM.
    inference_platform: str | None = None
    #: The paper's model group (§3.3). Decides the harness, the generation
    #: settings and, with §F, how the model was served.
    group: str = 'large'

    @property
    def reasoning(self) -> bool:
        return self.group == 'reasoning'

    @property
    def deployment_type(self) -> str:
        """§F: small conventional LLMs ran locally, everything else on an API."""
        if self.inference_platform is None:
            return 'self_deployed'
        return 'externally_managed'

    @property
    def inference_engine(self) -> InferenceEngine | None:
        """§F: the locally served models ran under vLLM; no version given."""
        if self.inference_platform is not None:
            return None
        return InferenceEngine(name='vLLM')

    @property
    def developer(self) -> str:
        """Developer, from the repo-wide helper: the id's org prefix."""
        return get_developer(self.model_id)



"""Mark a record as produced by the scheduled ingestion run.

A cron-produced record is otherwise indistinguishable from one a person
generated by hand, which makes a later correction ("re-do everything this
adapter published on this day") an unbounded scan. These keys make that
query answerable, including the one the ticket defers on purpose: which of
``deployment_type`` and ``model_availability`` were left as ``unknown``,
recorded per record so back-filling them is a filter rather than a re-read of
the whole datastore.

They live in ``source_metadata.additional_details``, a free-form
``dict[str, str]`` in both the schema and the generated model, so nothing here
requires a schema change. Stamping happens *after* de-duplication
fingerprinting, because ``cron_run_date`` changes daily and would otherwise
make every record look new on every run.
"""

from __future__ import annotations

import json
from datetime import date
from typing import Any

from every_eval_ever.eval_types import EvaluationLog

#: Marks the record as machine-ingested rather than hand-submitted.
TYPE_OF_ADDITION_KEY = 'type_of_addition'
TYPE_OF_ADDITION_VALUE = 'cron'
#: UTC date the cron pulled the source, ISO 8601 (``2026-08-10``).
RUN_DATE_KEY = 'cron_run_date'
#: Registry key of the adapter that produced the record.
ADAPTER_KEY = 'cron_adapter'
#: Link back to the run that produced it, when running in CI.
RUN_URL_KEY = 'cron_run_url'
#: Which inferred model fields came out ``unknown``, comma-separated. Present
#: only when at least one did.
UNKNOWN_INFERRED_KEY = 'cron_unknown_inferred_fields'

CRON_PROVENANCE_KEYS = (
    TYPE_OF_ADDITION_KEY,
    RUN_DATE_KEY,
    ADAPTER_KEY,
    RUN_URL_KEY,
    UNKNOWN_INFERRED_KEY,
)

#: Model metadata axes a source almost never states, so the schema defaults
#: them to ``unknown``. The ticket says to leave them that way for now and
#: fix them later; naming them per record is what makes "later" a query
#: instead of a re-read of every file.
INFERRED_FIELD_KEYS = ('deployment_type', 'model_availability')
UNKNOWN_VALUE = 'unknown'


def unknown_inferred_fields(record: dict[str, Any]) -> list[str]:
    """Return the inferred model fields this record leaves as ``unknown``.

    Both live in ``model_info.additional_details`` and both default to
    ``unknown`` in the generated model, so a record that omits one is saying
    the same thing as a record that spells it out.
    """
    model_info = record.get('model_info')
    details = (
        model_info.get('additional_details')
        if isinstance(model_info, dict)
        else None
    )
    if not isinstance(details, dict):
        details = {}
    return [
        key
        for key in INFERRED_FIELD_KEYS
        if details.get(key, UNKNOWN_VALUE) == UNKNOWN_VALUE
    ]


class ProvenanceConflictError(ValueError):
    """Raised when an adapter already set a cron provenance key differently.

    Overwriting would destroy whatever the adapter meant by it, so the run
    stops instead.
    """


def cron_provenance(
    *,
    adapter: str,
    run_date: date,
    run_url: str | None = None,
) -> dict[str, str]:
    """Return the provenance keys for one scheduled run."""
    if not adapter:
        raise ValueError('adapter is required for cron provenance')
    details = {
        TYPE_OF_ADDITION_KEY: TYPE_OF_ADDITION_VALUE,
        RUN_DATE_KEY: run_date.isoformat(),
        ADAPTER_KEY: adapter,
    }
    if run_url:
        details[RUN_URL_KEY] = run_url
    return details


def stamp_cron_provenance(
    record: dict[str, Any],
    *,
    adapter: str,
    run_date: date,
    run_url: str | None = None,
) -> dict[str, Any]:
    """Return ``record`` with cron provenance in ``source_metadata``.

    The input is not modified. The result is re-validated as an
    ``EvaluationLog`` so a stamp can never be the thing that ships an invalid
    record.
    """
    if not isinstance(record, dict):
        raise TypeError('record must be a decoded JSON object')

    stamped = json.loads(json.dumps(record))
    source_metadata = stamped.get('source_metadata')
    if not isinstance(source_metadata, dict):
        raise ValueError(
            'record has no source_metadata object to stamp; got '
            f'{type(source_metadata).__name__}'
        )

    details = source_metadata.get('additional_details')
    if details is None:
        details = {}
    elif not isinstance(details, dict):
        raise ValueError(
            'source_metadata.additional_details must be an object, got '
            f'{type(details).__name__}'
        )

    provenance = cron_provenance(
        adapter=adapter, run_date=run_date, run_url=run_url
    )
    unknown = unknown_inferred_fields(stamped)
    if unknown:
        provenance[UNKNOWN_INFERRED_KEY] = ','.join(unknown)
    for key, value in provenance.items():
        existing = details.get(key)
        if existing is not None and existing != value:
            raise ProvenanceConflictError(
                f'source_metadata.additional_details.{key} is already '
                f'{existing!r}; refusing to overwrite it with {value!r}'
            )
    details.update(provenance)
    source_metadata['additional_details'] = details

    # Re-validate through the same model the publisher and validator use.
    EvaluationLog.model_validate(stamped)
    return stamped


def is_cron_record(record: dict[str, Any]) -> bool:
    """Return whether a decoded record carries the cron marker."""
    source_metadata = record.get('source_metadata')
    if not isinstance(source_metadata, dict):
        return False
    details = source_metadata.get('additional_details')
    if not isinstance(details, dict):
        return False
    return details.get(TYPE_OF_ADDITION_KEY) == TYPE_OF_ADDITION_VALUE


